// Writes the token ABIs and bytecode where the app can import them, so the browser can deploy them.
// Run after `hardhat build`: npm run contracts:export

import { readFileSync, writeFileSync } from "node:fs";

const CONTRACTS = [
  { name: "CommunityToken", exportName: "communityToken" },
  { name: "RwaToken", exportName: "rwaToken" },
];
const OUTPUT = "lib/cctp/artifacts.ts";
// AGENTS.md has every source file copy its license header from here.
const HEADER_SOURCE = "app/page.tsx";
const HEADER_END = " */";

const headerSource = readFileSync(HEADER_SOURCE, "utf8");
const header = headerSource.slice(0, headerSource.indexOf(HEADER_END) + HEADER_END.length);

const exports = CONTRACTS.map(({ name, exportName }) => {
  const artifact = JSON.parse(readFileSync(`artifacts/contracts/${name}.sol/${name}.json`, "utf8"));
  return [
    `export const ${exportName}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;`,
    `export const ${exportName}Bytecode = ${JSON.stringify(artifact.bytecode)} as const;`,
  ].join("\n\n");
});

writeFileSync(
  OUTPUT,
  `${header}\n\n// Generated by scripts/export-artifacts.ts from contracts/. Don't edit by hand.\n\n${exports.join("\n\n")}\n`,
);
console.log(`Wrote ${OUTPUT}`);
